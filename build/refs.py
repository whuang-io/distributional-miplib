def render(key):
    authors, title, venue, details, year, url, proc, *rest = REFS[key]
    links = [("paper", url)] + (rest[0] if rest else [])
    link_html = ", ".join(f'<a href="{u}">{label}</a>' for label, u in links)
    venue_html = ("In " if proc else "") + f"<em>{venue}</em>" + (f", {details}" if details else "")
    return (f'<p class="ref" id="ref-{key}"><span class="ref-key">[{key}]</span> '
            f'{authors.rstrip(".")}. "{title}." {venue_html}, {year}. [{link_html}]</p>')
